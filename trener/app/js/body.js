/**
 * Собирает разметку фигуры. side — 'front' или 'back'.
 * Половина выводится дважды, вторая отражена через scale(-1,1).
 * Именно дважды, а не через <use>: копия <use> живёт в теневом дереве,
 * и клик по ней не доходит до path — тап по левой руке был бы мёртвым.
 */
function bodySvg(side) {
  const set = side === 'back' ? BACK_MUSCLES : FRONT_MUSCLES;
  const half = `<g class="base">${SILHOUETTE}</g>` +
    set.map(g => `<path class="grp" data-m="${g.m}" d="${g.d}"/>`).join('');

  return `
<svg class="figure" viewBox="0 0 120 258" aria-label="Что нагружено сегодня">
  <g>${half}</g>
  <g transform="translate(120,0) scale(-1,1)">${half}</g>
</svg>`;
}
